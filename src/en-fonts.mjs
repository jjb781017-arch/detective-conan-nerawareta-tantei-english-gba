export const FACES = { BOLD9, THIN7, COND7, COND6, COND6B, COND5, COND5B, MINI7, MINI8, MINI9, TITLE5 };

// Validate every face: rectangular, known characters, no stray symbols.
for (const [name, face] of Object.entries(FACES)) {
  for (const [ch, rows] of Object.entries(face)) {
    if (!rows.length) throw new Error(`${name} ${ch}: empty`);
    const w = rows[0].length;
    for (const r of rows) {
      if (r.length !== w) throw new Error(`${name} '${ch}': row width ${r.length} != ${w} (${r})`);
      if (!/^[#.]+$/.test(r)) throw new Error(`${name} '${ch}': bad row ${r}`);
    }
  }
}

export const glyphSize = (face) => {
  const any = Object.values(face)[0];
  return { w: any[0].length, h: any.length };
};

export const textWidth = (face, text, tracking = 1) => {
  const { w } = glyphSize(face);
  return [...text].length * (w + tracking) - tracking;
};
