// Font library for the English recreations.
//
// Every face is a plain object of glyph -> array of equal-length strings.
// '#' = ink. The renderer decides what colour the ink becomes, so the same
// letterform can be hollow, filled, bevelled or shadowed per asset.
//
// Faces:
//   BOLD9   9x12, 2px stems   - the "bold plate" face (YES/NO, LEVEL, menus)
//   THIN7   7x12, 1px stems   - light inline text
//   COND7   7x12, 2px stems   - condensed bold, for long strings in narrow bars
//   COND6   6x12, 1px stems   - extreme condensed, for 96px-wide bars
