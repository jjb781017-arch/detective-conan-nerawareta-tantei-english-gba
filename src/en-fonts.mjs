// The comic assets (starbursts, the CORRECT! stamp) set a tilted exclamation
// mark. The Japanese ！ leans like a "/" - bar top-right, dot bottom-left - so
// the bar is pre-sheared here, row by row, on top of whatever slant the draw
// spec applies to the rest of the word. A half-glyph shift was tried first and
// left a visible kink in the middle of the bar, so this shears the whole glyph
// along a straight line.
const leanBang = (rows, lean = 2) =>
  rows.map((r, i) => {
    const dx = Math.round(((rows.length - 1 - i) * lean) / (rows.length - 1));
    return dx > 0
      ? '.'.repeat(dx) + r.slice(0, r.length - dx)
      : r.slice(-dx) + '.'.repeat(-dx);
  });

