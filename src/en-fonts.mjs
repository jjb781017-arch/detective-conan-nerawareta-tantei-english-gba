// 5x12 ultra-condensed: THIN7 with its two most expendable interior columns
// removed. Used for the comic bursts, where an English word carries twice as
// many letters as the kana it replaces: 8 letters in the 115px the kana occupy
// means 15px per letter, so at 3x the face has to be 5px wide to reach the 36px
// height of the original lettering. The single-pixel stroke is deliberate - one
// 1px dilation brings it to 5px, which keeps the counters open behind the 1px
// white outline instead of closing them up like the 2px-stem faces do.
export const COND5 = condense(THIN7, 2);

// 5x12 condensed bold: COND7 resampled to 5px wide at a 0.35 coverage
// threshold, which keeps the two-pixel stems. Used where a long word has to fit
// the width the kana occupied but must stay as heavy as the rest of the family
// (the 9-glyph GAME OVER is the case that needs it).
export const COND5B = resampleFace(COND7, 5, 12, 0.35);

// 7x9 compact face for plates whose rows are only 9px apart. BOLD9 is resampled
// 9x12 -> 7x9 with a coverage rule: an output pixel is ink when at least 45% of
// its source cell is ink. Two-pixel stems survive as one-pixel stems and the
// counters stay open, so the compact face keeps the family's weight.
export function resampleFace(glyphs, dw, dh, threshold = 0.45) {
  const first = Object.values(glyphs)[0];
  const sw = first[0].length, sh = first.length;
  const out = {};
  for (const [ch, rows] of Object.entries(glyphs)) {
    const g = [];
    for (let y = 0; y < dh; y++) {
      let line = '';
      for (let x = 0; x < dw; x++) {
        let ink = 0, total = 0;
        const y0 = (y * sh) / dh, y1 = ((y + 1) * sh) / dh;
        const x0 = (x * sw) / dw, x1 = ((x + 1) * sw) / dw;
        for (let sy = Math.floor(y0); sy < Math.ceil(y1); sy++) {
          for (let sx = Math.floor(x0); sx < Math.ceil(x1); sx++) {
            const wy = Math.min(y1, sy + 1) - Math.max(y0, sy);
            const wx = Math.min(x1, sx + 1) - Math.max(x0, sx);
            if (wy <= 0 || wx <= 0) continue;
            total += wy * wx;
            if (rows[sy]?.[sx] === '#') ink += wy * wx;
          }
        }
        line += total && ink / total >= threshold ? '#' : '.';
      }
      g.push(line);
    }
    out[ch] = g;
  }
  return out;
}

