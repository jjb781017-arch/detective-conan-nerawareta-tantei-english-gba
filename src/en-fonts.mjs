// 6x12 extreme condensed, derived from THIN7 by dropping the single most
// expendable interior column of each glyph. Keeps the 1px stroke of THIN7 but
// buys one pixel per character, which is what the 96px-wide bars need.
function condense(glyphs, drop = 1) {
  const out = {};
  for (const [ch, rows] of Object.entries(glyphs)) {
    const w = rows[0].length;
    const cols = [];
    for (let c = 1; c < w - 1; c++) {
      let n = 0;
      for (const r of rows) if (r[c] === '#') n++;
      cols.push({ c, n, mid: Math.abs(c - (w - 1) / 2) });
    }
    cols.sort((a, b) => a.n - b.n || a.mid - b.mid);
    const kill = new Set(cols.slice(0, drop).map((k) => k.c));
    out[ch] = rows.map((r) => [...r].filter((_, c) => !kill.has(c)).join(''));
  }
  return out;
}

export const COND6 = condense(THIN7, 1);

// 6x12 *bold* condensed: COND7 with its single most expendable interior column
// removed. The 2px stems survive, so long strings in a tight burst keep the
// weight of the rest of the family instead of thinning out.
function condenseBold(glyphs, drop = 1) {
  const out = {};
  for (const [ch, rows] of Object.entries(glyphs)) {
    const w = rows[0].length;
    const cols = [];
    for (let c = 2; c < w - 2; c++) {
      let n = 0;
      for (const r of rows) if (r[c] === '#') n++;
      cols.push({ c, n, mid: Math.abs(c - (w - 1) / 2) });
    }
    cols.sort((a, b) => a.n - b.n || a.mid - b.mid);
    const kill = new Set(cols.slice(0, drop).map((k) => k.c));
    out[ch] = rows.map((r) => [...r].filter((_, c) => !kill.has(c)).join(''));
  }
  return out;
}

